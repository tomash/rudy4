# extconf.rb — stand-in for mkmf, for an extension whose "C compiler" is GDC.
#
# RubyGems knows how to run an extconf.rb + make + make install cycle for an
# extension; it does not care that the language is D. This file writes a
# Makefile that compiles `hello_gem.d` together with the rudy4 library into
# `hello_gem.so`, then exposes an `install` target that RubyGems will call.
#
# The rudy4 D library sources are found, in order, from:
#   1. $RUDY4_ROOT/src/rudy            (explicit override)
#   2. ../../../src/rudy               (in-repo development, this checkout)
# A published, standalone gem would instead vendor these sources into the
# gem (or declare a dependency on a `rudy4` gem that ships them).

require "rbconfig"
require "pathname"

RUDY4_ROOT =
  if ENV["RUDY4_ROOT"] && !ENV["RUDY4_ROOT"].empty?
    Pathname.new(ENV["RUDY4_ROOT"])
  else
    # ext/hello_gem/extconf.rb -> repo root is four levels up
    Pathname.new(__dir__).join("..", "..", "..", "..").expand_path
  end

RUDY_SRC = RUDY4_ROOT.join("src", "rudy").expand_path
unless RUDY_SRC.join("defs.d").file?
  abort <<~MSG
    rudy4 library sources not found at #{RUDY_SRC}.
    Set RUDY4_ROOT to a rudy4 checkout, or run extconf.rb from inside one.
  MSG
end

RUDY_D_SOURCES = Dir.glob(RUDY_SRC.join("**", "*.d")).sort

# Where RubyGems wants the built extension installed. `make install` below
# honours it; a plain `ruby extconf.rb && make` leaves the .so next to the
# sources (lib/) so it can be required in place.
RUBYARCHDIR = ENV["RUBYARCHDIR"] || File.expand_path("../../lib", __dir__)

hdr      = RbConfig::CONFIG["rubyhdrdir"]
archhdr  = RbConfig::CONFIG["rubyarchhdrdir"]
libarg   = RbConfig::CONFIG["LIBRUBYARG_SHARED"]
libdir   = RbConfig::CONFIG["libdir"]
dllib    = RbConfig::CONFIG["DLEXT"] # "so"

gdc = ENV["GDC"] || "gdc-14"

File.write("Makefile", <<~MAKE)
  # Generated by extconf.rb — do not edit.
  GDC         = #{gdc}
  RUBYHDR     = #{hdr}
  RUBYARCHHDR = #{archhdr}
  LIBRUBYARG  = #{libarg}
  LIBRUBY_DIR = #{libdir}
  RUBYARCHDIR = #{RUBYARCHDIR}

  DFLAGS = -fPIC -I#{RUDY4_ROOT.join("src")} -I$(RUBYHDR) -I$(RUBYARCHHDR) -fpreview=dip1008 -Wno-deprecated

  RUDY_SOURCES = #{RUDY_D_SOURCES.join(" ")}

  TARGET = hello_gem_ext.#{dllib}

  all: $(TARGET)

  $(TARGET): hello_gem.d $(RUDY_SOURCES)
  \t$(GDC) -shared -o $@ $(DFLAGS) $(RUDY_SOURCES) hello_gem.d \\
  \t  -L$(LIBRUBY_DIR) $(LIBRUBYARG) -lm

  install: $(TARGET)
  \tmkdir -p $(RUBYARCHDIR)
  \tcp $(TARGET) $(RUBYARCHDIR)/

  clean:
  \trm -f $(TARGET)
MAKE
